const TEST_TIMEOUT: Duration = Duration::from_secs(5);

/// WHY: A streaming provider reassembler must survive extreme transport
/// packetization without dropping or corrupting bytes. This test proves that
/// delivering an SSE response at 1 byte per TCP write arrives byte-for-byte
/// identical to the script.
///
/// What it does not catch: Transport-layer bit flips or TLS record corruption.
#[tokio::test]
async fn an_sse_body_delivered_at_1_byte_per_write_arrives_byte_identical_to_script() {
	timeout(TEST_TIMEOUT, async {
		let engine = Engine::bind().await.expect("bind loopback engine");
		let raw_payload =
			b"event: message\ndata: {\"text\":\"hello world\",\"idx\":1}\n\nevent: done\ndata: [DONE]\n\n";

		// Chunk size 1 byte
		let script = ResponseScript::sse_stream(raw_payload, 1);
		assert_eq!(script.chunks.len(), raw_payload.len());

		engine.route("/v1/chat", script);

		let mut stream = TcpStream::connect(engine.addr())
			.await
			.expect("connect to engine");
		let req =
			format!("GET /v1/chat HTTP/1.1\r\nHost: {}\r\nConnection: close\r\n\r\n", engine.addr());
		stream
			.write_all(req.as_bytes())
			.await
			.expect("write request");

		let mut resp_bytes = Vec::new();
		stream
			.read_to_end(&mut resp_bytes)
			.await
			.expect("read response");

		let resp_str = String::from_utf8_lossy(&resp_bytes);
		assert!(resp_str.starts_with("HTTP/1.1 200 OK\r\n"));
		assert!(
			resp_str
				.to_ascii_lowercase()
				.contains("content-type: text/event-stream")
		);

		// Extract body after \r\n\r\n
		let body_start = resp_bytes
			.windows(4)
			.position(|w| w == b"\r\n\r\n")
			.expect("found header delimiter")
			+ 4;
		let received_body = &resp_bytes[body_start..];
		assert_eq!(received_body, raw_payload, "1-byte writes must arrive byte-identical");
	})
	.await
	.expect("test must terminate within bounded deadline");
}

/// WHY: Multi-byte UTF-8 code points (e.g. emojis or CJK characters) may be
/// split across TCP packet boundaries. This test proves that the engine can
/// split a multi-byte UTF-8 sequence across chunk boundaries and that the
/// receiver can reconstruct the valid UTF-8 string.
///
/// What it does not catch: Invalid unicode scalar values generated by model
/// bugs.
#[tokio::test]
async fn an_event_split_mid_utf8_sequence_reassembles_correctly() {
	timeout(TEST_TIMEOUT, async {
		let engine = Engine::bind().await.expect("bind loopback engine");
		// "🦀" is 4 bytes: [0xF0, 0x9F, 0xA6, 0x80]
		let crab = "🦀";
		assert_eq!(crab.len(), 4);

		let mut script = ResponseScript::sse();
		// First chunk: "data: {\"emoji\": \"" + first 2 bytes of crab
		let mut chunk1 = Vec::from(b"data: {\"emoji\": \"".as_slice());
		chunk1.extend_from_slice(&crab.as_bytes()[..2]);
		script = script.chunk(Bytes::from(chunk1));

		// Second chunk: last 2 bytes of crab + "\"}\n\n"
		let mut chunk2 = Vec::from(&crab.as_bytes()[2..]);
		chunk2.extend_from_slice(b"\"}\n\n");
		script = script.chunk(Bytes::from(chunk2));

		engine.route("/v1/utf8", script);

		let mut stream = TcpStream::connect(engine.addr())
			.await
			.expect("connect to engine");
		let req =
			format!("GET /v1/utf8 HTTP/1.1\r\nHost: {}\r\nConnection: close\r\n\r\n", engine.addr());
		stream
			.write_all(req.as_bytes())
			.await
			.expect("write request");

		let mut resp_bytes = Vec::new();
		stream
			.read_to_end(&mut resp_bytes)
			.await
			.expect("read response");

		let body_start = resp_bytes
			.windows(4)
			.position(|w| w == b"\r\n\r\n")
			.expect("found header delimiter")
			+ 4;
		let received_body = &resp_bytes[body_start..];
		let body_text =
			std::str::from_utf8(received_body).expect("split UTF-8 must reassemble into valid UTF-8");
		assert_eq!(body_text, "data: {\"emoji\": \"🦀\"}\n\n");
	})
	.await
	.expect("test must terminate within bounded deadline");
}

/// WHY: HTTP/1.1 connection reuse (Keep-Alive) must process multiple sequential
/// requests on a single TCP connection without state leaking between requests.
///
/// What it does not catch: HTTP/2 multiplexed streams over one connection.
#[tokio::test]
async fn keep_alive_serves_two_requests_on_one_connection() {
	timeout(TEST_TIMEOUT, async {
		let engine = Engine::bind().await.expect("bind loopback engine");
		engine
			.route("/req1", ResponseScript::ok().raw_body(Bytes::from_static(b"{\"response\": 1}")));
		engine
			.route("/req2", ResponseScript::ok().raw_body(Bytes::from_static(b"{\"response\": 2}")));

		let mut stream = TcpStream::connect(engine.addr())
			.await
			.expect("connect to engine");

		// First request with keep-alive
		let req1 =
			format!("GET /req1 HTTP/1.1\r\nHost: {}\r\nConnection: keep-alive\r\n\r\n", engine.addr());
		stream.write_all(req1.as_bytes()).await.expect("write req1");

		// Read response 1 headers + body
		let mut buf = [0u8; 1024];
		let n1 = stream.read(&mut buf).await.expect("read resp1");
		let resp1 = String::from_utf8_lossy(&buf[..n1]);
		assert!(resp1.contains("HTTP/1.1 200 OK"));
		assert!(resp1.contains("{\"response\": 1}"));

		// Second request on the SAME connection
		let req2 =
			format!("GET /req2 HTTP/1.1\r\nHost: {}\r\nConnection: close\r\n\r\n", engine.addr());
		stream.write_all(req2.as_bytes()).await.expect("write req2");

		let mut remaining = Vec::new();
		stream
			.read_to_end(&mut remaining)
			.await
			.expect("read resp2 to end");
		let resp2 = String::from_utf8_lossy(&remaining);
		assert!(resp2.contains("HTTP/1.1 200 OK"));
		assert!(resp2.contains("{\"response\": 2}"));

		assert_eq!(engine.request_count(), 2);
	})
	.await
	.expect("test must terminate within bounded deadline");
}

/// WHY: A malformed HTTP request line or header must be cleanly answered with
/// HTTP 400 Bad Request and connection closed, rather than hanging or
/// panicking.
