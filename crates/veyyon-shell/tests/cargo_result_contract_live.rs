//! Live smoke: real `cargo` quiet / color / json output through the minimizer.
//!
//! Skips when `cargo` is not on PATH. Uses a tiny no-deps crate so `--offline`
//! does not need crates.io.

use std::{fs, process::Command};

use veyyon_shell::minimizer::{self, MinimizerConfig};
use veyyon_test_scratch::{TempTree, scratch_dir};

fn cargo_available() -> bool {
	Command::new("cargo")
		.arg("-V")
		.output()
		.is_ok_and(|out| out.status.success())
}

fn temp_crate() -> TempTree {
	let dir = scratch_dir("cargo-contract");
	fs::create_dir_all(dir.join("src")).expect("temp src");
	fs::write(
		dir.join("Cargo.toml"),
		"[package]\nname = \"contract_smoke\"\nversion = \"0.1.0\"\nedition = \"2021\"\n",
	)
	.expect("manifest");
	fs::write(
		dir.join("Cargo.lock"),
		"# This file is automatically @generated by Cargo.\nversion = 3\n\n[[package]]\nname = \
		 \"contract_smoke\"\nversion = \"0.1.0\"\n",
	)
	.expect("lockfile");
	fs::write(dir.join("src/lib.rs"), "#[test]\nfn it_works() {\n\tassert_eq!(2 + 2, 4);\n}\n")
		.expect("lib");
	dir
}

fn minimize(command: &str, captured: &str, exit: i32) -> String {
	let config =
		MinimizerConfig { enabled: true, max_capture_bytes: u32::MAX, ..Default::default() };
	minimizer::apply(command, captured, exit, &config).text
}

fn run_cargo(dir: &std::path::Path, args: &[&str], env: &[(&str, &str)]) -> (String, i32) {
	let mut cmd = Command::new("cargo");
	cmd.args(args).current_dir(dir);
	for (key, value) in env {
		cmd.env(key, value);
	}
	let out = cmd.output().expect("spawn cargo");
	let mut text = String::from_utf8_lossy(&out.stdout).into_owned();
	text.push_str(&String::from_utf8_lossy(&out.stderr));
	(text, out.status.code().unwrap_or(1))
}

#[test]
fn live_cargo_quiet_color_and_json_headers() {
	if !cargo_available() {
		return;
	}
	let dir = temp_crate();

	let (quiet, quiet_exit) = run_cargo(
		&dir,
		&["test", "--quiet", "--offline", "--manifest-path", "Cargo.toml"],
		&[("CARGO_TERM_QUIET", "true")],
	);
	let quiet_out = minimize("cargo test --quiet --offline", &quiet, quiet_exit);
	assert!(
		quiet_exit == 0 && quiet_out.starts_with("[clean] cargo test"),
		"quiet: exit={quiet_exit} out={quiet_out:?} raw={quiet:?}"
	);

	let (color, color_exit) = run_cargo(
		&dir,
		&["test", "--offline", "--manifest-path", "Cargo.toml"],
		&[("CARGO_TERM_COLOR", "always")],
	);
	let color_out = minimize("cargo test --offline", &color, color_exit);
	assert!(
		color_exit == 0 && color_out.starts_with("[clean] cargo test"),
		"color: exit={color_exit} out={color_out:?} raw={color:?}"
	);
	assert!(!color_out.contains('\u{1b}'), "ansi must be stripped: {color_out:?}");

	let (json, json_exit) = run_cargo(
		&dir,
		&["check", "--message-format=json", "--offline", "--manifest-path", "Cargo.toml"],
		&[],
	);
	let json_out = minimize("cargo check --message-format=json --offline", &json, json_exit);
	assert!(
		json_exit == 0 && json_out.starts_with("[clean] cargo check"),
		"json: exit={json_exit} out={json_out:?} raw={json:?}"
	);
}
